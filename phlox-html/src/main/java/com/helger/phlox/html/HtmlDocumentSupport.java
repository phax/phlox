package com.helger.phlox.html;

import java.nio.charset.StandardCharsets;

import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;

import com.helger.base.io.stream.StreamHelper;
import com.helger.base.string.StringReplace;
import com.helger.css.property.CCSSProperties;
import com.helger.html.css.DefaultCSSClassProvider;
import com.helger.html.css.ICSSClassProvider;
import com.helger.html.hc.html.HC_Target;
import com.helger.html.hc.html.grouping.HCDiv;
import com.helger.html.hc.html.metadata.HCMeta;
import com.helger.html.hc.html.metadata.HCStyle;
import com.helger.html.hc.html.root.HCHtml;
import com.helger.html.hc.html.textlevel.HCA;
import com.helger.io.resource.ClassPathResource;
import com.helger.phlox.api.PhloxDocumentProperties;
import com.helger.phlox.api.model.PhloxInvoice;
import com.helger.phlox.api.watermark.PhloxProgramWatermark;
import com.helger.phlox.api.watermark.WatermarkSpec;
import com.helger.url.SimpleURL;

/**
 * Parts of the HTML document that {@link HtmlTemplateEmitter} adds around the content of the
 * template: the document head with the embedded stylesheet, the watermarks and the page wrapper.
 *
 * @author Philip Helger
 */
final class HtmlDocumentSupport
{
  /** The project page the program watermark links to. */
  private static final String PROJECT_URL = PhloxDocumentProperties.PROJECT_URL;
  /** The name of the browser window the project page is opened in. */
  private static final String PROJECT_WINDOW_NAME = "phlox";

  /** The classpath location of the default stylesheet; <code>{p}</code> stands for the class prefix. */
  private static final String DEFAULT_CSS_PATH = "phlox-default.tcss";

  /** The distance of a watermark at the top or the bottom from the edge of the page. */
  private static final String EDGE_DISTANCE = "4mm";

  private HtmlDocumentSupport ()
  {}

  @NonNull
  private static String _cssVariables (@NonNull final HtmlRenderContext aCtx)
  {
    if (aCtx.getCssVariables ().isEmpty ())
      return "";
    final StringBuilder aSB = new StringBuilder ("\n:root{");
    aCtx.getCssVariables ().forEach ( (sName, sValue) -> aSB.append (sName).append (':').append (sValue).append (';'));
    return aSB.append ('}').toString ();
  }

  private static void _addMetaElement (@NonNull final HCHtml aHtml,
                                       @NonNull final String sName,
                                       @Nullable final String sContent)
  {
    if (sContent != null && !sContent.isEmpty ())
      aHtml.head ().metaElements ().add (new HCMeta ().setName (sName).setContent (sContent));
  }

  @NonNull
  static ICSSClassProvider cls (@NonNull final String sName)
  {
    return DefaultCSSClassProvider.create (sName);
  }

  /**
   * Create the program watermark, i.e. the "generated by" footer. The text links to the project page
   * and opens it in the window named {@code phlox}. In contrast to the user watermark it is
   * clickable and therefore not hidden from assistive technology. Only the text of the spec is used:
   * the look and the place of the footer come from the stylesheet.
   *
   * @param aSpec
   *        The program watermark. Never {@code null}.
   * @param sCssClass
   *        The CSS class of the footer. Never {@code null}.
   * @return The footer element. Never {@code null}.
   */
  @NonNull
  static HCDiv createProgramWatermark (@NonNull final WatermarkSpec aSpec, @NonNull final String sCssClass)
  {
    final HCDiv aD = new HCDiv ().addClass (cls (sCssClass));
    aD.addChild (new HCA (new SimpleURL (PROJECT_URL)).setTarget (new HC_Target (PROJECT_WINDOW_NAME))
                                                      .addChild (aSpec.getText ()));
    return aD;
  }

  /**
   * Create the user watermark. All values of the spec override the stylesheet. Like in the PDF, only
   * the centred watermark is rotated. A watermark that repeats on every page is <code>fixed</code>,
   * which a browser prints on every page; any other one is <code>absolute</code> and stays on the
   * first page.
   *
   * @param aSpec
   *        The user watermark. Never {@code null}.
   * @param sCssClass
   *        The CSS class of the watermark. Never {@code null}.
   * @return The watermark element. Never {@code null}.
   */
  @NonNull
  static HCDiv createWatermark (@NonNull final WatermarkSpec aSpec, @NonNull final String sCssClass)
  {
    final HCDiv aD = new HCDiv ().addClass (cls (sCssClass));
    aD.addChild (aSpec.getText ());
    aD.addStyle (CCSSProperties.COLOR.newValue (aSpec.getCssRgba ()));
    aD.addStyle (CCSSProperties.FONT_SIZE.newValue (aSpec.getFontSizePt () + "pt"));
    aD.addStyle (CCSSProperties.POSITION.newValue (aSpec.isRepeatPerPage () ? "fixed" : "absolute"));
    switch (aSpec.getPosition ())
    {
      case TOP ->
      {
        aD.addStyle (CCSSProperties.TOP.newValue (EDGE_DISTANCE));
        aD.addStyle (CCSSProperties.LEFT.newValue ("50%"));
        aD.addStyle (CCSSProperties.TRANSFORM.newValue ("translateX(-50%)"));
      }
      case BOTTOM ->
      {
        aD.addStyle (CCSSProperties.TOP.newValue ("auto"));
        aD.addStyle (CCSSProperties.BOTTOM.newValue (EDGE_DISTANCE));
        aD.addStyle (CCSSProperties.LEFT.newValue ("50%"));
        aD.addStyle (CCSSProperties.TRANSFORM.newValue ("translateX(-50%)"));
      }
      case FOOTER_RIGHT ->
      {
        aD.addStyle (CCSSProperties.TOP.newValue ("auto"));
        aD.addStyle (CCSSProperties.LEFT.newValue ("auto"));
        aD.addStyle (CCSSProperties.BOTTOM.newValue (EDGE_DISTANCE));
        aD.addStyle (CCSSProperties.RIGHT.newValue (EDGE_DISTANCE));
        aD.addStyle (CCSSProperties.TRANSFORM.newValue ("none"));
      }
      default ->
      {
        aD.addStyle (CCSSProperties.TOP.newValue ("50%"));
        aD.addStyle (CCSSProperties.LEFT.newValue ("50%"));
        aD.addStyle (CCSSProperties.TRANSFORM.newValue ("translate(-50%,-50%) rotate(" +
                                                        aSpec.getRotation () +
                                                        "deg)"));
      }
    }
    aD.customAttrs ().putIn ("aria-hidden", "true");
    return aD;
  }

  /** Embedded default stylesheet - prefix-aware. */
  @NonNull
  static String defaultCss (@NonNull final String sPrefix)
  {
    final String sCss = StreamHelper.getAllBytesAsString (new ClassPathResource (DEFAULT_CSS_PATH),
                                                          StandardCharsets.UTF_8);
    if (sCss == null)
      throw new IllegalStateException ("Failed to read the classpath resource '" + DEFAULT_CSS_PATH + "'");
    return StringReplace.replaceAll (sCss, "{p}", sPrefix);
  }

  /**
   * Fill the head of the document and add the watermarks and the page wrapper to the body. Without
   * the embedded default stylesheet the variables, the fonts and the custom stylesheet are still
   * written.
   *
   * @param aHtml
   *        The document to fill. Never {@code null}.
   * @param aInvoice
   *        The invoice, for the title and the metadata. Never {@code null}.
   * @param aCtx
   *        The render context. Never {@code null}.
   * @return The page wrapper to add the content to. Never {@code null}.
   */
  @NonNull
  static HCDiv createPage (@NonNull final HCHtml aHtml,
                           @NonNull final PhloxInvoice aInvoice,
                           @NonNull final HtmlRenderContext aCtx)
  {
    final String sPrefix = aCtx.getCssClassPrefix ();

    aHtml.setLanguage (aCtx.getLocale ().toLanguageTag ());

    // The writer produces UTF-8, and a browser needs to be told so for the characters that are not
    // ASCII (umlauts, Cyrillic, Greek, ...)
    aHtml.head ().metaElements ().add (new HCMeta ().setCharset (StandardCharsets.UTF_8));
    aHtml.head ().setPageTitle (PhloxDocumentProperties.getTitle (aInvoice, aCtx));
    _addMetaElement (aHtml, "generator", PhloxDocumentProperties.getGenerator ());
    _addMetaElement (aHtml, "author", PhloxDocumentProperties.getAuthor (aInvoice));
    _addMetaElement (aHtml, "description", PhloxDocumentProperties.getSubject (aInvoice, aCtx));
    _addMetaElement (aHtml, "keywords", PhloxDocumentProperties.getKeywords (aInvoice, aCtx));
    final String sCss = (aCtx.isEmbeddedStylesheet () ? defaultCss (sPrefix) : "") +
                        _cssVariables (aCtx) +
                        (aCtx.getFontFamily () == null ? "" : "\n" + aCtx.getFontFamily ().getCss ()) +
                        (aCtx.getCustomStylesheet () == null ? "" : "\n" + aCtx.getCustomStylesheet ());
    if (!sCss.isEmpty ())
    {
      final HCStyle aStyle = new HCStyle ();
      aStyle.setStyleContent (sCss.stripLeading ());
      aHtml.head ().addCSS (aStyle);
    }

    final WatermarkSpec aUW = aCtx.getUserWatermark ();
    if (aUW != null)
      aHtml.body ().addChild (createWatermark (aUW, sPrefix + "watermark-user"));
    final WatermarkSpec aPW = PhloxProgramWatermark.getInstance ();
    if (aPW != null)
      aHtml.body ().addChild (createProgramWatermark (aPW, sPrefix + "watermark-program"));

    final HCDiv aPage = new HCDiv ().addClass (cls (sPrefix + "page"));
    aHtml.body ().addChild (aPage);
    return aPage;
  }
}
