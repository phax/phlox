package com.helger.phlox.api.watermark;

import org.jspecify.annotations.Nullable;

/**
 * Library-wide attribution watermark. Distinguishes the open-source distribution from any
 * commercial repackaging at runtime. Not part of {@link com.helger.phlox.api.AbstractRenderContext}
 * because it is a distribution-time choice, not a per-render one.
 * <p>
 * The open-source build defaults to a small low-opacity footer-right attribution. The
 * commercial distribution typically calls {@link #setInstance(WatermarkSpec) setInstance(null)}
 * in its bootstrap (e.g. behind a license check) to suppress the watermark, or replaces it
 * with a different one (e.g. its own vendor brand).
 * <p>
 * The library is Apache-licensed: the watermark is overrideable by design and is not a DRM
 * mechanism.
 * <p>
 * The program watermark is a footer with a link, not a watermark like the user one, so the writers
 * use only a part of the {@link WatermarkSpec}. All use the text. The PDF writer also uses the
 * colour, the opacity and the font size, and always sets it right-aligned in the footer of every
 * page. The HTML writer takes the look and the place from its stylesheet (class
 * <code>watermark-program</code>). The plain-text writer writes the text as last line.
 *
 * @author Philip Helger
 */
public final class PhloxProgramWatermark
{
  private static final WatermarkSpec OPEN_SOURCE_DEFAULT = WatermarkSpec
                                                                       .text ("Generated by phlox · open-source edition · github.com/phax/phlox")
                                                                       .setOpacity (0.35f)
                                                                       .setRotation (0f)
                                                                       .setPosition (EWatermarkPosition.FOOTER_RIGHT)
                                                                       .setFontSizePt (6f)
                                                                       .setRepeatPerPage (true);

  private static volatile WatermarkSpec s_aActive = OPEN_SOURCE_DEFAULT;

  private PhloxProgramWatermark ()
  {}

  /**
   * Replace (or with {@code null}, suppress) the library-wide program watermark. Typically
   * called once at JVM startup; the commercial distribution invokes this from a static
   * initializer behind a license check.
   *
   * @param aSpec
   *        The new watermark spec, or {@code null} to suppress the watermark entirely.
   */
  public static void setInstance (@Nullable final WatermarkSpec aSpec)
  {
    s_aActive = aSpec;
  }

  /**
   * Get the currently active program watermark spec, or {@code null} if suppressed.
   *
   * @return The currently active program watermark spec, or {@code null} if suppressed.
   */
  @Nullable
  public static WatermarkSpec getInstance ()
  {
    return s_aActive;
  }

  /** Restore the open-source default watermark. Useful for tests that mutated the instance. */
  public static void resetToOpenSourceDefault ()
  {
    s_aActive = OPEN_SOURCE_DEFAULT;
  }
}
